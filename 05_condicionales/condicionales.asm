
INCLUDE Irvine32.inc

.data

.code
main PROC
	
	mov ebx, 1 ; VALOR INICIAL PAARA INCREMENTAR
	
ciclo:
	cmp ebx, 10 ; CONDICIONND DE SALIDA
	
	jg fin ; SALTO A FINALIZAR EL CODIGO CUANDO SE CUPLA LA CONDICION DE SALIDA

	mov eax, ebx ; SE COPIA EL VALOR DE EBX A EAX PARA DESPLEGARLO EN CONSOLA
	call WriteDec ; DESPLIEGA EN CONSOLA EL NUEMRO QUE SE INCREMETA
	call Crlf ; SALTO DE LINEA

	inc ebx ; RALIZA EL INCREMENTO DE +1 EN EL REGUISTRO SEÑALADP (EBX)

	jmp ciclo ; SALTO SIN CONDICION PARA REPETIR EL CODIGO MIENTRAS NO SE SIGA CUMPLIENDO
	

fin:
	exit

main ENDP
END main

